package com.smartnutrient.app

/**
 * One row is one recognisable recipe. Oil and salt are selected when logging a
 * meal and are deliberately not expanded into duplicate catalogue entries.
 */
internal fun buildDishes(): List<CatalogSpec> = curatedDishRows().map { dish ->
    val metadata = DISH_SEARCH_METADATA[dish.name]
    CatalogSpec(
        name = dish.name,
        pinyin = metadata?.pinyin.orEmpty(),
        initials = metadata?.initials.orEmpty(),
        category = "菜",
        basis = "熟重",
        kcal = dish.kcal,
        protein = dish.protein,
        fat = dish.fat,
        sat = dish.fat * 0.2,
        carbs = dish.carbs,
        fiber = dish.fiber,
        sugar = 0.0,
        sodium = dish.sodium,
        potassium = 210.0,
        cholesterol = if (dish.ingredients.any { it.containsAny("蛋", "鱼", "虾", "肉", "鸡", "骨", "肝", "蛤") }) 45.0 else 20.0,
        aliases = metadata?.aliases.orEmpty(),
        ingredients = dish.ingredients,
        method = dish.method,
        source = "真实菜名 + 标准食材配方估算",
        confidence = "估算",
    )
}

private data class DishSpec(
    val name: String,
    val kcal: Double,
    val protein: Double,
    val fat: Double,
    val carbs: Double,
    val fiber: Double,
    val sodium: Double,
    val ingredients: List<String>,
    val method: String,
)

private data class DishSearchMetadata(
    val pinyin: String,
    val initials: String,
    val aliases: List<String> = emptyList(),
)

private fun meta(pinyin: String, initials: String, vararg aliases: String) =
    DishSearchMetadata(pinyin, initials, aliases.toList())

private fun curatedDishRows(): List<DishSpec> = listOf(
    VEGETABLE_ROWS,
    MEAT_ROWS,
    POULTRY_ROWS,
    SEAFOOD_ROWS,
    EGG_TOFU_ROWS,
    SOUP_AND_MEAL_ROWS,
).flatMap { block ->
    block.trimIndent().lineSequence()
        .filter { it.isNotBlank() }
        .map(::parseDishRow)
        .toList()
}

private fun String.containsAny(vararg values: String): Boolean = values.any(::contains)

private fun parseDishRow(row: String): DishSpec {
    val cells = row.split('|')
    require(cells.size == 9) { "Malformed dish row: $row" }
    return DishSpec(
        name = cells[0],
        kcal = cells[1].toDouble(),
        protein = cells[2].toDouble(),
        fat = cells[3].toDouble(),
        carbs = cells[4].toDouble(),
        fiber = cells[5].toDouble(),
        sodium = cells[6].toDouble(),
        ingredients = cells[7].split(',').filter { it.isNotBlank() },
        method = cells[8],
    )
}

