/** Kept separate from FoodCatalog's name-deduplication so raw ingredients never shadow cooked dishes. */
object RawIngredientCatalog {
    val items: List<FoodItem> = buildList {
        val seenNames = mutableSetOf<String>()
        (ingredientSpecs() + expandedIngredientSpecs()).forEachIndexed { index, spec ->
            if (seenNames.add(spec.name)) add(spec.toFoodForFreeform(50_000 + index))
        }
    }
}

private fun CatalogSpec.toFoodForFreeform(id: Int) = FoodItem(
    id, name, pinyin, initials, category, basis,
    FoodNutrients(
        kcal, protein, fat, sat, carbs, fiber, sugar, sodium, potassium, cholesterol,
        SugarDataPolicy.addedSugarG(category, name, sugar),
    ),
    aliases, ingredients, method, source, confidence,
)

/** Unified display/search catalog: prepared foods, standalone ingredients, seasonings and supplements. */
object EntryFoodCatalog {
    val items: List<FoodItem> = buildList {
        val seenNames = mutableSetOf<String>()
        (FoodCatalog.items + RawIngredientCatalog.items + SeasoningCatalog.foods).forEach { food ->
            val key = "${food.category}:${food.name}"
            if (seenNames.add(key)) add(food)
        }
        DrinkCatalog.items.forEach { food ->
            val key = "${food.category}:${food.name}"
            if (seenNames.add(key)) add(food)
        }
        SupplementCatalog.items.forEach { food ->
            val key = "${food.category}:${food.name}"
            if (seenNames.add(key)) add(food)
        }
        AdditionalFoodCatalog.items.forEach { food ->
            val key = "${food.category}:${food.name}"
            if (seenNames.add(key)) add(food)
        }
    }
}

